// إزالة التشكيل وتوحيد صور الحروف المتشابهة (أ إ آ → ا، ة → ه، ى → ي...)
// عشان البحث ما يفشل بسبب اختلافات الكتابة الشائعة.
function normalize(text) {
  return String(text || '')
    .replace(/[\u064B-\u065F\u0670]/g, '') // تشكيل
    .replace(/[إأآا]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

// كلمات وظيفية (أدوات ربط/استفهام) لا تحمل معنى موضوعياً — نتجاهلها بالبحث
// عشان ما تسبب نتائج زائفة (مثل "الذي" أو "فيه" اللي بتتطابق مع أي حديث تقريباً).
const STOPWORDS = new Set([
  'الذي', 'التي', 'الذين', 'اللذين', 'اللتين', 'اللواتي',
  'في', 'فيه', 'فيها', 'من', 'الى', 'الي', 'على', 'عن', 'مع', 'او', 'و',
  'هو', 'هي', 'هم', 'ما', 'هل', 'كيف', 'اين', 'متى', 'لماذا', 'كل', 'بين',
  'حديث', 'الحديث', 'احاديث', 'الاحاديث', 'رسول', 'الرسول', 'نبي', 'النبي',
  'صلى', 'وسلم', 'عليه',
]);

// توسيع كل كلمة بالاستعلام بمرادفاتها المعروفة (إن وُجدت)
function expandQuery(query) {
  const words = normalize(query).split(' ').filter((w) => w && !STOPWORDS.has(w));
  const expanded = new Set();
  words.forEach((word) => {
    expanded.add(word);
    Object.entries(SYNONYMS).forEach(([key, syns]) => {
      const normKey = normalize(key);
      const normSyns = syns.map(normalize);
      if (normSyns.includes(word) || normKey === word) {
        normSyns.forEach((s) => expanded.add(s));
        expanded.add(normKey);
      }
    });
  });
  return Array.from(expanded);
}

// ترتيب نتائج البحث حسب عدد الكلمات الموسّعة المطابقة (كلما طابق أكثر، ظهر أول)
function searchHadiths(hadiths, query) {
  const q = (query || '').trim();
  if (!q) return hadiths;
  const terms = expandQuery(q);
  const scored = hadiths
    .map((h) => {
      const catName = (categories.find((c) => c.id === h.category) || {}).name || '';
      const haystack = normalize(`${h.text} ${(h.keywords || []).join(' ')} ${h.narrator || ''} ${catName}`);
      let score = 0;
      terms.forEach((term) => {
        if (term.length >= 2 && haystack.includes(term)) score += 1;
      });
      return { h, score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.map((x) => x.h);
}

// تصنيف نص حديث تلقائياً: يرجع أول تصنيف تتطابق كلماته المفتاحية مع النص،
// وإلا يرجع تصنيف "أحكام ومعاملات عامة" الافتراضي.
function classify(text) {
  const norm = normalize(text);
  for (const cat of categories) {
    if (!cat.keywords.length) continue;
    if (cat.keywords.some((k) => norm.includes(normalize(k)))) return cat.id;
  }
  return 'ahkam';
}

module.exports = { categories, normalize, expandQuery, searchHadiths, classify };
